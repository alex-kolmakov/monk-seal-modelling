"""Write prototype/bathymetry.js from the EMODnet file the model uses.

Source: data/real_long/bathymetry_emodnet.nc.

Elevation in metres (negative = sea) is stored as base64 int16, row 0 = north, so the page works
from file:// without a server. Values are rounded down, so a sea cell (elevation below 0) never
reads as land (>= 0) on the page, as it would after rounding to the nearest metre.

    uv run python prototype/build_bathymetry.py
"""

import base64
from pathlib import Path

import numpy as np
import xarray as xr

HERE = Path(__file__).parent
SRC = HERE.parent / "data" / "real_long" / "bathymetry_emodnet.nc"
LON0, LON1, LAT0, LAT1 = -17.3, -16.2, 32.3, 32.95
W, H = 264, 156  # 1/240 degree, about 0.4 km


def main() -> None:
    with xr.open_dataset(SRC) as ds:
        box = ds["elevation"].sel(lat=slice(LAT0, LAT1), lon=slice(LON0, LON1)).load()
    elev = box.values[::-1]  # north first
    assert elev.shape == (H, W), elev.shape
    raw = np.clip(np.floor(elev), -32768, 32767).astype("<i2").tobytes()
    out = HERE / "bathymetry.js"
    out.write_text(
        "// EMODnet Bathymetry DTM (mean), elevation in m, negative = sea."
        " Generated by build_bathymetry.py\n"
        f"window.BATHY={{w:{W},h:{H},lon0:{LON0},lon1:{LON1},lat0:{LAT0},lat1:{LAT1},"
        f'elev:"{base64.b64encode(raw).decode()}"}};\n'
    )
    print(out, out.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
